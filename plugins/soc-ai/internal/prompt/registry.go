func register(id, body string) {
	sum := sha256.Sum256([]byte(body))
	byID[id] = Template{
		ID:     id,
		Body:   body,
		SHA256: hex.EncodeToString(sum[:]),
	}
}

// Require returns the registered template or panics on unknown id (programming error).
func Require(id string) Template {
	initRegistry()
	t, ok := byID[id]
	if !ok {
		panic(fmt.Sprintf("unknown prompt id: %s", id))
	}
	return t
}

// Find returns a template by id.
func Find(id string) (Template, bool) {
	initRegistry()
	t, ok := byID[id]
	return t, ok
}

// SHA256Hex returns lowercase hex SHA-256 of body (UTF-8).
func SHA256Hex(body string) string {
	sum := sha256.Sum256([]byte(body))
	return hex.EncodeToString(sum[:])
}
